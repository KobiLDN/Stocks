"""Build the generated pages from templates (rebuild step 5, #73).

    python site/build.py            # write the generated pages
    python site/build.py --check    # fail if any generated page is out of date (CI)

Templates live in site/templates/, per-sector values in site/sectors.yaml, and ticker
names come from universe.yaml. Generated files are committed (so Cloudflare keeps
serving plain static files and PR previews work exactly as before). Edit the template
or the config, run this, commit the result. Never edit a generated page by hand.
"""
import json
import os
import sys

import yaml
from jinja2 import Environment, FileSystemLoader, StrictUndefined

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
BANNER = "<!-- GENERATED by site/build.py from site/templates/{tpl} — edit the template or site/sectors.yaml, not this file -->\n"


def load():
    with open(os.path.join(HERE, "sectors.yaml"), encoding="utf-8") as f:
        sectors = yaml.safe_load(f)
    with open(os.path.join(ROOT, "universe.yaml"), encoding="utf-8") as f:
        universe = yaml.safe_load(f)
    return sectors, universe


def sector_names(universe, sector):
    """{ticker: company name} for one sector, in display order (fallback names for the pages)."""
    return {t: universe["assets"][t]["name"] for t, _ in universe["sectors"][sector]}


def render_all():
    """{relative output path: file text} for every generated page."""
    sectors, universe = load()
    env = Environment(loader=FileSystemLoader(os.path.join(HERE, "templates")), undefined=StrictUndefined,
                      trim_blocks=True, lstrip_blocks=True, keep_trailing_newline=True)
    out = {}
    tpl = env.get_template("signals.html.j2")
    for sector, s in sectors["signals"].items():
        names = json.dumps(sector_names(universe, sector), ensure_ascii=False, indent=4).replace("\n", "\n  ")
        html = tpl.render(s=s, sector=sector, names_json=names)
        out[f"{sector}/signals.html"] = html.replace("<!DOCTYPE html>\n", "<!DOCTYPE html>\n" + BANNER.format(tpl="signals.html.j2"), 1)
    return out


def main(argv):
    pages = render_all()
    if "--check" in argv:
        stale = [p for p, text in pages.items()
                 if not os.path.exists(os.path.join(ROOT, p)) or open(os.path.join(ROOT, p), encoding="utf-8").read() != text]
        if stale:
            print("Generated pages are out of date — run: python site/build.py")
            for p in stale:
                print("  stale:", p)
            return 1
        print(f"{len(pages)} generated pages are up to date")
        return 0
    for p, text in pages.items():
        with open(os.path.join(ROOT, p), "w", encoding="utf-8", newline="\n") as f:
            f.write(text)
    print(f"wrote {len(pages)} pages")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
