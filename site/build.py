"""Build the generated pages from templates (rebuild step 5, #73).

    python site/build.py            # write the generated pages
    python site/build.py --check    # fail if any generated page is out of date (CI)

Templates live in site/templates/, per-sector values in site/sectors.yaml, and ticker
names come from universe.yaml. Generated files are committed (so Cloudflare keeps
serving plain static files and PR previews work exactly as before). Edit the template
or the config, run this, commit the result. Never edit a generated page by hand.
"""
import json
import os
import sys

import yaml
from jinja2 import Environment, FileSystemLoader, StrictUndefined

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
BANNER = "<!-- GENERATED by site/build.py from site/templates/{tpl} — edit the template or site/sectors.yaml, not this file -->\n"


def load():
    with open(os.path.join(HERE, "sectors.yaml"), encoding="utf-8") as f:
        sectors = yaml.safe_load(f)
    with open(os.path.join(ROOT, "universe.yaml"), encoding="utf-8") as f:
        universe = yaml.safe_load(f)
    return sectors, universe


def sector_names(universe, sector):
    """{ticker: company name} for one sector, in display order (fallback names for the pages)."""
    return {t: universe["assets"][t]["name"] for t, _ in universe["sectors"][sector]}


def with_count(s, universe, sector):
    """Fill {count} in a page description with the sector's size from universe.yaml."""
    return {**s, "meta_description": s["meta_description"].replace("{count}", str(len(universe["sectors"][sector])))}


def render_all():
    """{relative output path: file text} for every generated page."""
    sectors, universe = load()
    env = Environment(loader=FileSystemLoader(os.path.join(HERE, "templates")), undefined=StrictUndefined,
                      trim_blocks=True, lstrip_blocks=True, keep_trailing_newline=True)
    out = {}
    tpl = env.get_template("signals.html.j2")
    for sector, s in sectors["signals"].items():
        names = json.dumps(sector_names(universe, sector), ensure_ascii=False, indent=4).replace("\n", "\n  ")
        html = tpl.render(s=s, sector=sector, names_json=names)
        out[f"{sector}/signals.html"] = html.replace("<!DOCTYPE html>\n", "<!DOCTYPE html>\n" + BANNER.format(tpl="signals.html.j2"), 1)
    mtpl = env.get_template("metrics.html.j2")
    base_tips = sectors["metrics_base_tips"]
    for sector, s in sectors["metrics"].items():
        s = with_count(s, universe, sector)
        tip = lambda key, s=s: {**base_tips[key], **s["tip_overrides"].get(key, {})}
        names = json.dumps(sector_names(universe, sector), ensure_ascii=False, indent=4).replace("\n", "\n  ")
        html = mtpl.render(s=s, sector=sector, tip=tip, names_json=names)
        out[f"{sector}/metrics.html"] = html.replace("<!DOCTYPE html>\n", "<!DOCTYPE html>\n" + BANNER.format(tpl="metrics.html.j2"), 1)
    ntpl = env.get_template("news.html.j2")
    for sector, s in sectors["news"].items():
        s = with_count(s, universe, sector)
        names = json.dumps(sector_names(universe, sector), ensure_ascii=False, indent=4).replace("\n", "\n  ")
        html = ntpl.render(s=s, sector=sector, names_json=names)
        out[f"{sector}/news.html"] = html.replace("<!DOCTYPE html>\n", "<!DOCTYPE html>\n" + BANNER.format(tpl="news.html.j2"), 1)
    ctpl = env.get_template("calculator.html.j2")
    for sector, s in sectors["calculator"].items():
        names = json.dumps(sector_names(universe, sector), ensure_ascii=False, indent=4).replace("\n", "\n  ")
        html = ctpl.render(s=s, sector=sector, names_json=names)
        out[f"{sector}/calculator.html"] = html.replace("<!DOCTYPE html>\n", "<!DOCTYPE html>\n" + BANNER.format(tpl="calculator.html.j2"), 1)
    htpl = env.get_template("charts.html.j2")
    for sector, s in sectors["charts"].items():
        html = htpl.render(s=s, sector=sector)
        out[f"{sector}/charts.html"] = html.replace("<!DOCTYPE html>\n", "<!DOCTYPE html>\n" + BANNER.format(tpl="charts.html.j2"), 1)
    hmtpl = env.get_template("heatmap.html.j2")
    for sector, s in sectors["heatmap"].items():
        names = json.dumps(sector_names(universe, sector), ensure_ascii=False, indent=2)
        html = hmtpl.render(s=s, sector=sector, names_json=names)
        out[f"{sector}/heatmap.html"] = html.replace("<!DOCTYPE html>\n", "<!DOCTYPE html>\n" + BANNER.format(tpl="heatmap.html.j2"), 1)
    dtpl = env.get_template("dashboard.html.j2")
    for sector, s in sectors["dashboard"].items():
        with open(os.path.join(HERE, "css", "dashboard", f"{sector}.css"), encoding="utf-8") as f:
            css = f.read()
        html = dtpl.render(s=s, sector=sector, css=css)
        out[f"{sector}/index.html"] = html.replace("<!DOCTYPE html>\n", "<!DOCTYPE html>\n" + BANNER.format(tpl="dashboard.html.j2"), 1)
    out["sector-data.js"] = sector_data_js(sectors)
    return out


# Sector keys as the All Sectors pages name them (All/index.html SECTORS list)
ALL_KEYS = {"AI": "ai", "Biotech": "biotech", "Crypto": "crypto", "Defence": "defence",
            "Energy": "energy", "MegaCap": "megacap", "Tech": "tech"}


def sector_data_js(sectors):
    """sector-data.js: the dashboards' notes, category colours and labels, for the All Sectors pages."""
    dash = sectors["dashboard"]
    data = {
        "notes": {ALL_KEYS[sec]: {n["id"]: n["text"] for n in s["notes"]} for sec, s in dash.items()},
        "catColors": {c["id"]: c["value"] for s in dash.values() for c in s["cat_colors"]},
        "catLabels": {c["id"]: c["label"] for s in dash.values() for c in s["cat_labels"]},
    }
    return ("// GENERATED by site/build.py from site/sectors.yaml (dashboard:) — edit that, not this file.\n"
            "// Used by the All Sectors pages so their notes, colours and labels match the sector dashboards.\n"
            "window.SECTOR_DATA = " + json.dumps(data, ensure_ascii=False, indent=1) + ";\n")


def main(argv):
    pages = render_all()
    if "--check" in argv:
        stale = [p for p, text in pages.items()
                 if not os.path.exists(os.path.join(ROOT, p)) or open(os.path.join(ROOT, p), encoding="utf-8").read() != text]
        if stale:
            print("Generated pages are out of date — run: python site/build.py")
            for p in stale:
                print("  stale:", p)
            return 1
        print(f"{len(pages)} generated files are up to date")
        return 0
    for p, text in pages.items():
        with open(os.path.join(ROOT, p), "w", encoding="utf-8", newline="\n") as f:
            f.write(text)
    print(f"wrote {len(pages)} files")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
