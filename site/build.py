"""Build the generated pages from templates (rebuild step 5, #73).

    python site/build.py            # write the generated pages
    python site/build.py --check    # fail if any generated page is out of date (CI)

Templates live in site/templates/, per-sector values in site/sectors.yaml, and ticker
names come from universe.yaml. Generated files are committed (so Cloudflare keeps
serving plain static files and PR previews work exactly as before). Edit the template
or the config, run this, commit the result. Never edit a generated page by hand.
"""
import json
import os
import sys

import yaml
from jinja2 import Environment, FileSystemLoader, StrictUndefined

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path.insert(0, ROOT)   # groups_config / universe (repo root)
BANNER = "<!-- GENERATED by site/build.py from site/templates/{tpl} — edit the template or site/sectors.yaml, not this file -->\n"


def load():
    with open(os.path.join(HERE, "sectors.yaml"), encoding="utf-8") as f:
        sectors = yaml.safe_load(f)
    with open(os.path.join(ROOT, "universe.yaml"), encoding="utf-8") as f:
        universe = yaml.safe_load(f)
    return sectors, universe


def sector_names(universe, sector):
    """{ticker: company name} for one sector, in display order (fallback names for the pages)."""
    return {t: universe["assets"][t]["name"] for t, _ in universe["sectors"][sector]}


def with_count(s, universe, sector):
    """Fill {count} in a page description with the sector's size from universe.yaml."""
    return {**s, "meta_description": s["meta_description"].replace("{count}", str(len(universe["sectors"][sector])))}


def render_all():
    """{relative output path: file text} for every generated page."""
    sectors, universe = load()
    env = Environment(loader=FileSystemLoader(os.path.join(HERE, "templates")), undefined=StrictUndefined,
                      trim_blocks=True, lstrip_blocks=True, keep_trailing_newline=True)
    out = {}
    tpl = env.get_template("signals.html.j2")
    for sector, s in sectors["signals"].items():
        names = json.dumps(sector_names(universe, sector), ensure_ascii=False, indent=4).replace("\n", "\n  ")
        html = tpl.render(s=s, sector=sector, names_json=names, root="../")
        out[f"{sector}/signals.html"] = html.replace("<!DOCTYPE html>\n", "<!DOCTYPE html>\n" + BANNER.format(tpl="signals.html.j2"), 1)
    mtpl = env.get_template("metrics.html.j2")
    base_tips = sectors["metrics_base_tips"]
    for sector, s in sectors["metrics"].items():
        s = with_count(s, universe, sector)
        tip = lambda key, s=s: {**base_tips[key], **s["tip_overrides"].get(key, {})}
        names = json.dumps(sector_names(universe, sector), ensure_ascii=False, indent=4).replace("\n", "\n  ")
        html = mtpl.render(s=s, sector=sector, tip=tip, names_json=names, root="../")
        out[f"{sector}/metrics.html"] = html.replace("<!DOCTYPE html>\n", "<!DOCTYPE html>\n" + BANNER.format(tpl="metrics.html.j2"), 1)
    ntpl = env.get_template("news.html.j2")
    for sector, s in sectors["news"].items():
        s = with_count(s, universe, sector)
        names = json.dumps(sector_names(universe, sector), ensure_ascii=False, indent=4).replace("\n", "\n  ")
        html = ntpl.render(s=s, sector=sector, names_json=names, root="../")
        out[f"{sector}/news.html"] = html.replace("<!DOCTYPE html>\n", "<!DOCTYPE html>\n" + BANNER.format(tpl="news.html.j2"), 1)
    ctpl = env.get_template("calculator.html.j2")
    for sector, s in sectors["calculator"].items():
        names = json.dumps(sector_names(universe, sector), ensure_ascii=False, indent=4).replace("\n", "\n  ")
        html = ctpl.render(s=s, sector=sector, names_json=names, root="../")
        out[f"{sector}/calculator.html"] = html.replace("<!DOCTYPE html>\n", "<!DOCTYPE html>\n" + BANNER.format(tpl="calculator.html.j2"), 1)
    htpl = env.get_template("charts.html.j2")
    for sector, s in sectors["charts"].items():
        html = htpl.render(s=s, sector=sector, root="../")
        out[f"{sector}/charts.html"] = html.replace("<!DOCTYPE html>\n", "<!DOCTYPE html>\n" + BANNER.format(tpl="charts.html.j2"), 1)
    hmtpl = env.get_template("heatmap.html.j2")
    for sector, s in sectors["heatmap"].items():
        names = json.dumps(sector_names(universe, sector), ensure_ascii=False, indent=2)
        html = hmtpl.render(s=s, sector=sector, names_json=names, root="../")
        out[f"{sector}/heatmap.html"] = html.replace("<!DOCTYPE html>\n", "<!DOCTYPE html>\n" + BANNER.format(tpl="heatmap.html.j2"), 1)
    dtpl = env.get_template("dashboard.html.j2")
    for sector, s in sectors["dashboard"].items():
        with open(os.path.join(HERE, "css", "dashboard", f"{sector}.css"), encoding="utf-8") as f:
            css = f.read()
        html = dtpl.render(s=s, sector=sector, css=css, root="../")
        out[f"{sector}/index.html"] = html.replace("<!DOCTYPE html>\n", "<!DOCTYPE html>\n" + BANNER.format(tpl="dashboard.html.j2"), 1)
    out["sector-data.js"] = sector_data_js(sectors)
    out.update(render_groups(env, sectors, universe))
    return out


# ── Market and sector group pages (#88) ─────────────────────────────────────────
GROUP_PAGES = [("dashboard", "index.html"), ("metrics", "metrics.html"), ("news", "news.html"),
               ("signals", "signals.html"), ("calculator", "calculator.html"), ("charts", "charts.html"),
               ("heatmap", "heatmap.html")]
DERIVED_SIGNALS = {"sp500", "nasdaq100"}     # generate_group_signals.py: picks from the sector runs
CHART_DEFAULT = {"sp500": "AAPL", "nasdaq100": "NVDA", "ftse100": "AZN"}


def group_configs(g, assets, base):
    """Per-page settings for one group: its own names, counts, categories and colours; shared wording
    (column tooltips, heatmap thresholds, dashboard styles) from the Technology pages (`base`)."""
    import groups_config as gc
    # labels and tooltips go into single-quoted JS strings in some templates: no straight apostrophes
    cats = [(c, l.replace("'", "’")) for c, l in gc.categories(g, assets)]
    col = gc.colours(cats)
    n, name = len(g["tickers"]), g["name"]
    what = "sector" if g["kind"] == "market" else "industry"
    labels = [{"id": c, "label": l} for c, l in cats]
    rgba = [{"id": c, "rgb": col[c][1], "bg": "0.1", "color": f"var(--{col[c][0]})", "border": "0.25"} for c, _ in cats]
    tips = [{"id": c, "text": f"{l} stocks in the {name}" if g["kind"] == "market" else f"{name}: {l}"} for c, l in cats]
    kind_word = "index" if g["kind"] == "market" else "sector"
    common = {"page_title": name, "h1": name, "unit": "stocks", "count": n, "t212": True,
              "group_kind": g["kind"]}
    by_cat = {}
    for t in g["tickers"]:
        by_cat.setdefault(gc.category_of(g, assets[t], cats), []).append(t)
    first = CHART_DEFAULT.get(g["id"]) or sorted(by_cat.get(cats[0][0], g["tickers"]))[0]
    tv = {t: gc.tradingview_symbol(t, assets[t]) for t in g["tickers"]}
    tv_map = "".join(f"\n    {json.dumps(t)}: {json.dumps(v)}," for t, v in sorted(tv.items())
                     if v != f"{assets[t]['exchange']}:{t}")
    chart_cats = "".join(
        f"\n    '{c}': {{\n      key: '{c}',\n      label: {json.dumps(l)},\n      color: 'var(--{col[c][0]})',\n"
        f"      btnLabel: {json.dumps(l)},\n      tooltip: {json.dumps(next(x['text'] for x in tips if x['id'] == c))},\n    }},"
        for c, l in cats)
    chart_css = "\n".join(
        [f"  .cat-btn.active-{c} {{ background: var(--{col[c][0]}); border-color: var(--{col[c][0]}); color: var(--bg); }}" for c, _ in cats]
        + [f"  .cat-label.{c} {{ color: var(--{col[c][0]}); }}" for c, _ in cats])
    return {
        "dashboard": {**common, "title": f"{name} — Dashboard",
                      "cat_css": "\n".join(f"  .cat-{c['id']} {{ background: rgba({c['rgb']},0.1); color: {c['color']}; "
                                           f"border: 1px solid rgba({c['rgb']},0.25); }}" for c in rgba),
                      "meta_description": f"{name} dashboard: live prices, 52-week ranges and returns for all {n} stocks in the {kind_word}.",
                      "chips": labels, "cat_colors": [{"id": c, "value": f"var(--{col[c][0]})"} for c, _ in cats],
                      "cat_labels": labels, "notes": []},
        "metrics": {**common, "meta_description": f"{name} stock fundamentals: P/E, market cap, beta, volume and analyst views for {n} stocks.",
                    "search_placeholder": base["metrics"]["search_placeholder"], "categories": rgba,
                    "cat_labels": labels, "cat_tooltips": tips, "tip_overrides": base["metrics"]["tip_overrides"]},
        "news": {**common, "meta_description": f"News for {name} stocks.",
                 "search_placeholder": base["news"]["search_placeholder"], "default_window": "day",
                 "empty_note": "News for the market and sector pages is not collected yet. It will cover each day’s "
                               "signal picks and biggest movers (#88), not all of these stocks.",
                 "categories": rgba, "cat_labels": labels, "cat_tooltips": tips},
        "calculator": {**common, "meta_description": f"What-If calculator: what $100 to $10,000 in {name} stocks would be worth now.",
                       "h1_word": "Calculator", "categories": rgba, "cat_labels": labels},
        "charts": {**common, "meta_description": f"1-year price charts for all {n} {name} stocks, by {what}.",
                   "old_count": n, "chart_ticker": first, "chart_name": assets[first]["name"], "symbol": tv[first],
                   "symbol_name": assets[first]["name"], "default_tf": "1W", "note_suffix": "", "tv_map_js": tv_map,
                   "chart_cats_js": chart_cats, "no_embed_js": "", "cls_suffix": {}, "sector_css": chart_css},
        "signals": {**common, "meta_description": (f"AI signals for the {name}: the sector runs' picks that are members."
                                                    if g["id"] in DERIVED_SIGNALS else
                                                    f"AI-generated top 10 buy signals for the {n} stocks in the {name}."),
                    "categories": rgba, "cat_labels": labels, "how_titles": [
                        "Live price data", "Web search for live catalysts",
                        "Picks from the sector runs" if g["id"] in DERIVED_SIGNALS else "AI ranking via DeepSeek",
                        "Mon/Wed/Fri refresh via GitHub Actions"],
                    "how": [
                        f"<code>update_group_prices.py</code> prices all {n} stocks three times a day: 1D/1W/1M/YTD and 1-year returns, "
                        "market cap, P/E, beta, dividend yield, short interest and the analyst view.",
                        "Before ranking, the model is told to search online for the latest news on the group's ten biggest "
                        "one-month movers, so its reasons can cite live catalysts.",
                        (f"The {name} is too big for one AI prompt, and narrowing it by recent strength first would favour "
                         "stocks that have just run up. So this page shows the picks of the 11 sector runs that are "
                         f"{name} members, best first by the AI's confidence." if g["id"] in DERIVED_SIGNALS else
                         f"<code>generate_group_signals.py</code> sends every {name} stock to <code>deepseek/deepseek-v4-flash</code> "
                         "via OpenRouter, which returns its top 10 with a reason for each. The momentum screen only adds notes; "
                         "it never changes the AI's pick."),
                        "Runs every Monday, Wednesday and Friday morning, after the prices update. Every run is recorded "
                        "with the list of stocks it could choose from, so the Track Record can judge it fairly."],
                    "disclaimer": "The model can be wrong, biased toward recent momentum, or inconsistent run-to-run. "
                                  "Signals are one input among many — always do your own research before making any investment decision.",
                    "refresh_note": "Auto-refreshed Mon / Wed / Fri · 08:00 London · GitHub Actions"},
        "heatmap": {**common, "meta_description": f"{name} heatmap: 1D, 1W, 1M, YTD and 1-year moves for all {n} stocks.",
                    "all_label": "All Stocks", "cat_label": f"By {what.capitalize()}", "n_cats": len(cats),
                    "cat_order": [c for c, _ in cats], "metrics_cfg_js": base["heatmap"]["metrics_cfg_js"],
                    "cat_labels": labels},
    }


def render_groups(env, sectors, universe):
    """Six pages per market/sector group, in markets/<id>/ and sectors/<slug>/ (two levels deep)."""
    import groups_config as gc
    assets = universe["assets"]
    base = {k: sectors[k]["Tech"] for k in ("metrics", "news", "heatmap")}
    with open(os.path.join(HERE, "css", "dashboard", "Tech.css"), encoding="utf-8") as f:
        css = f.read()
    base_tips = sectors["metrics_base_tips"]
    out = {}
    for g in gc.all_groups(assets):
        cfg = group_configs(g, assets, base)
        names = json.dumps({t: assets[t]["name"] for t in g["tickers"]}, ensure_ascii=False, indent=1)
        for page, file in GROUP_PAGES:
            s = cfg[page]
            extra = {"css": css + "\n  /* this group's categories (#88) */\n" + s["cat_css"] + "\n"} if page == "dashboard" else {}
            if page == "metrics":
                extra["tip"] = lambda key, s=s: {**base_tips[key], **s["tip_overrides"].get(key, {})}
            html = env.get_template(f"{page}.html.j2").render(s=s, sector=g["id"], names_json=names, root="../../", **extra)
            out[f"{g['path']}/{file}"] = html.replace("<!DOCTYPE html>\n", "<!DOCTYPE html>\n" + BANNER.format(tpl=f"{page}.html.j2"), 1)
    return out


# Sector keys as the All Sectors pages name them (All/index.html SECTORS list)
ALL_KEYS = {"AI": "ai", "Biotech": "biotech", "Crypto": "crypto", "Defence": "defence",
            "Energy": "energy", "MegaCap": "megacap", "Tech": "tech"}


def sector_data_js(sectors):
    """sector-data.js: the dashboards' notes, category colours and labels, for the All Sectors pages."""
    dash = sectors["dashboard"]
    data = {
        "notes": {ALL_KEYS[sec]: {n["id"]: n["text"] for n in s["notes"]} for sec, s in dash.items()},
        "catColors": {c["id"]: c["value"] for s in dash.values() for c in s["cat_colors"]},
        "catLabels": {c["id"]: c["label"] for s in dash.values() for c in s["cat_labels"]},
    }
    return ("// GENERATED by site/build.py from site/sectors.yaml (dashboard:) — edit that, not this file.\n"
            "// Used by the All Sectors pages so their notes, colours and labels match the sector dashboards.\n"
            "window.SECTOR_DATA = " + json.dumps(data, ensure_ascii=False, indent=1) + ";\n")


def main(argv):
    pages = render_all()
    if "--check" in argv:
        stale = [p for p, text in pages.items()
                 if not os.path.exists(os.path.join(ROOT, p)) or open(os.path.join(ROOT, p), encoding="utf-8").read() != text]
        if stale:
            print("Generated pages are out of date — run: python site/build.py")
            for p in stale:
                print("  stale:", p)
            return 1
        print(f"{len(pages)} generated files are up to date")
        return 0
    for p, text in pages.items():
        with open(os.path.join(ROOT, p), "w", encoding="utf-8", newline="\n") as f:
            f.write(text)
    print(f"wrote {len(pages)} files")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
